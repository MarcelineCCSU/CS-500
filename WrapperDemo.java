public class WrapperDemo
{
  public static void main ( String[] args )
  {
     Integer val1 = 1;
     System.out.println( val1 );

     Integer val2 = 2;
     System.out.println( val2 );

    // Calculating Sum
    System.out.println( val1+val2 );

    // Example with another type
    Character another = 'a' ;
    System.out.println(another);
  }
}
